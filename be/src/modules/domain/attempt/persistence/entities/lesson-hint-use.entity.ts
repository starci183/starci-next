import { Column, Entity, PrimaryGeneratedColumn, Unique } from "typeorm"

@Entity("lesson_hint_uses")
@Unique("lesson_hint_uses_natural_key", ["learnerId", "lessonId", "scenarioId"])
/** One scenario hint a learner asked for: the lesson then reads "có hỗ trợ". Written once per learner, lesson and scenario. */
export class LessonHintUseEntity {
    /** The learner. */
    @Column({ name: "learner_id", type: "uuid" })
    learnerId!: string

    /** The lesson. */
    @Column({ name: "lesson_id", type: "text" })
    lessonId!: string

    /** The scenario whose hint was shown. */
    @Column({ name: "scenario_id", type: "text" })
    scenarioId!: string

    /** When the hint was first asked for. */
    @Column({ name: "used_at", type: "timestamptz" })
    usedAt!: Date

    /** The row id, generated by the database; the former key is the unique `<table>_natural_key`. */
    @PrimaryGeneratedColumn("uuid", { name: "id" })
    id!: string
}
