import { Column, Entity, PrimaryGeneratedColumn, Unique } from "typeorm"

@Entity("lesson_section_reads")
@Unique("lesson_section_reads_natural_key", ["learnerId", "lessonId", "sectionId"])
/** One article section a learner marked as read: it clears the "nên đọc kỹ" mark. Written once per learner, lesson and section. */
export class LessonSectionReadEntity {
    /** The learner. */
    @Column({ name: "learner_id", type: "uuid" })
    learnerId!: string

    /** The lesson. */
    @Column({ name: "lesson_id", type: "text" })
    lessonId!: string

    /** The section. */
    @Column({ name: "section_id", type: "text" })
    sectionId!: string

    /** When the section was first marked. */
    @Column({ name: "read_at", type: "timestamptz" })
    readAt!: Date

    /** The row id, generated by the database; the former key is the unique `<table>_natural_key`. */
    @PrimaryGeneratedColumn("uuid", { name: "id" })
    id!: string
}
