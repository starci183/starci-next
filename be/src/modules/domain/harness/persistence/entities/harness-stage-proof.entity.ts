import { Column, Entity, PrimaryGeneratedColumn, Unique } from "typeorm"

@Entity("harness_stage_proofs")
@Unique("harness_stage_proofs_natural_key", ["learnerId", "buildId", "stageId", "e2eId", "runId"])
/** One e2e result of an attested CI run of a bound repository: only attested results are stored here. */
export class HarnessStageProofEntity {
    /** The learner. */
    @Column({ name: "learner_id", type: "uuid" })
    learnerId!: string

    /** The build. */
    @Column({ name: "build_id", type: "text" })
    buildId!: string

    /** The stage. */
    @Column({ name: "stage_id", type: "text" })
    stageId!: string

    /** The e2e test id. */
    @Column({ name: "e2e_id", type: "text" })
    e2eId!: string

    /** The CI run id. */
    @Column({ name: "run_id", type: "text" })
    runId!: string

    /** Whether it passed. */
    @Column({ name: "passed", type: "boolean" })
    passed!: boolean

    /** The commit it ran on. */
    @Column({ name: "commit_sha", type: "text", nullable: true })
    commitSha!: string | null

    /** The binding whose repository posted the run. */
    @Column({ name: "binding_id", type: "uuid" })
    bindingId!: string

    /** When it was recorded. */
    @Column({ name: "recorded_at", type: "timestamptz" })
    recordedAt!: Date

    /** The row id, generated by the database; the former key is the unique `<table>_natural_key`. */
    @PrimaryGeneratedColumn("uuid", { name: "id" })
    id!: string
}
